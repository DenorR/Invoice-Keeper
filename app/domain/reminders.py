"""Окно напоминания: за сколько дней до срока бот пишет в чат."""

from __future__ import annotations

# Меньше трёх дней выставить нельзя: кейс требует напоминать не позже чем за 3 дня до срока.
MIN_DAYS = 3
MAX_DAYS = 365


def clamp_days(days: int) -> int:
    """Значение из базы или .env, приведённое к допустимому диапазону (на случай старых записей)."""
    return max(MIN_DAYS, min(MAX_DAYS, days))
